"""Generate table-driven CRC implementations in C, Python and Rust."""

from __future__ import annotations

import re

from . import __version__
from .crc import CrcAlgorithm, crc_table, reflect_bits

LANGUAGES = ("c", "python", "rust")


class CodegenError(ValueError):
    pass


def identifier(name: str) -> str:
    cleaned = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower() or "crc"
    return f"crc_{cleaned}" if cleaned[0].isdigit() else cleaned


def _register_bits(algorithm: CrcAlgorithm) -> int:
    return algorithm.width if algorithm.refin else max(algorithm.width, 8)


def _type_bits(bits: int) -> int:
    for size in (8, 16, 32, 64):
        if bits <= size:
            return size
    raise CodegenError(f"{bits}-bit registers do not fit a native integer; use --lang python for widths above 64.")


def _start_register(algorithm: CrcAlgorithm) -> int:
    register = reflect_bits(algorithm.init, algorithm.width) if algorithm.refin else algorithm.init
    if not algorithm.refin:
        register <<= max(algorithm.width, 8) - algorithm.width
    return register


def _header_lines(algorithm: CrcAlgorithm, function: str) -> list[str]:
    lines = [
        f"{function}: {algorithm.reveng_spec()}",
    ]
    if algorithm.check is not None:
        digits = max(1, (algorithm.width + 3) // 4)
        lines.append(f'check: {function}("123456789") == 0x{algorithm.check:0{digits}X}')
    lines.append(f"Generated by CRCForge {__version__}.")
    return lines


def _format_table(values: tuple[int, ...], digits: int, per_line: int, suffix: str, indent: str) -> str:
    rows = []
    for start in range(0, len(values), per_line):
        chunk = values[start : start + per_line]
        rows.append(indent + ", ".join(f"0x{value:0{digits}X}{suffix}" for value in chunk) + ",")
    return "\n".join(rows)


def generate(algorithm: CrcAlgorithm, language: str, function: str | None = None) -> str:
    if not isinstance(algorithm, CrcAlgorithm):
        raise CodegenError("Code generation supports CRC algorithms.")
    language = language.lower()
    if language not in LANGUAGES:
        raise CodegenError(f"Unsupported language: {language}. Choose one of: {', '.join(LANGUAGES)}.")
    name = identifier(function or algorithm.name)
    if language == "python":
        return _python(algorithm, name)
    if language == "c":
        return _c(algorithm, name)
    return _rust(algorithm, name)


def _table(algorithm: CrcAlgorithm) -> tuple[int, ...]:
    return crc_table(algorithm.width, algorithm.poly, algorithm.refin)


def _python(algorithm: CrcAlgorithm, name: str) -> str:
    width = algorithm.width
    register_bits = _register_bits(algorithm)
    digits = max(2, (register_bits + 3) // 4)
    shift = register_bits - width
    header = "\n".join(_header_lines(algorithm, name))
    lines = [
        f'"""{header}"""',
        "",
        f"_{name.upper()}_TABLE = (",
        _format_table(_table(algorithm), digits, max(4, 64 // digits), "", "    "),
        ")",
        "",
        "",
        f"def {name}(data: bytes) -> int:",
        f"    table = _{name.upper()}_TABLE",
        f"    crc = 0x{_start_register(algorithm):0{digits}X}",
        "    for byte in data:",
    ]
    if algorithm.refin:
        lines.append("        crc = table[(crc ^ byte) & 0xFF] ^ (crc >> 8)")
    else:
        mask = (1 << register_bits) - 1
        lines.append(
            f"        crc = table[((crc >> {register_bits - 8}) ^ byte) & 0xFF] ^ ((crc << 8) & 0x{mask:0{digits}X})"
        )
    if shift:
        lines.append(f"    crc >>= {shift}")
    if algorithm.refout != algorithm.refin:
        lines.append(f'    crc = int(f"{{crc:0{width}b}}"[::-1], 2)')
    out_digits = max(1, (width + 3) // 4)
    lines.append(f"    return crc ^ 0x{algorithm.xor_out:0{out_digits}X}")
    return "\n".join(lines) + "\n"


def _c(algorithm: CrcAlgorithm, name: str) -> str:
    width = algorithm.width
    register_bits = _register_bits(algorithm)
    type_bits = _type_bits(register_bits)
    ctype = f"uint{type_bits}_t"
    suffix = "ULL" if type_bits == 64 else "U"
    digits = max(2, (register_bits + 3) // 4)
    out_digits = max(1, (width + 3) // 4)
    shift = register_bits - width
    header = "\n".join(f" * {line}" for line in _header_lines(algorithm, name))
    lines = [
        "/*",
        header,
        " */",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"static const {ctype} {name}_table[256] = {{",
        _format_table(_table(algorithm), digits, max(4, 64 // (digits + 4)), suffix, "    "),
        "};",
        "",
    ]
    if algorithm.refout != algorithm.refin:
        lines.extend(
            [
                f"static {ctype} {name}_reflect({ctype} value)",
                "{",
                f"    {ctype} result = 0;",
                f"    for (int bit = 0; bit < {width}; ++bit) {{",
                "        result = (result << 1) | (value & 1);",
                "        value >>= 1;",
                "    }",
                "    return result;",
                "}",
                "",
            ]
        )
    lines.extend(
        [
            f"{ctype} {name}(const void *data, size_t length)",
            "{",
            "    const uint8_t *bytes = (const uint8_t *)data;",
            f"    {ctype} crc = 0x{_start_register(algorithm):0{digits}X}{suffix};",
            "    while (length--) {",
        ]
    )
    if algorithm.refin:
        step = f"{name}_table[(crc ^ *bytes++) & 0xFF]"
        if register_bits > 8:
            step += " ^ (crc >> 8)"
        lines.append(f"        crc = ({ctype})({step});")
    else:
        step = f"{name}_table[((crc >> {register_bits - 8}) ^ *bytes++) & 0xFF]"
        if register_bits > 8:
            step += " ^ (crc << 8)"
        if register_bits < type_bits:
            mask = (1 << register_bits) - 1
            step = f"({step}) & 0x{mask:0{digits}X}{suffix}"
        lines.append(f"        crc = ({ctype})({step});")
    lines.append("    }")
    if shift:
        lines.append(f"    crc >>= {shift};")
    if algorithm.refout != algorithm.refin:
        lines.append(f"    crc = {name}_reflect(crc);")
    lines.extend([f"    return ({ctype})(crc ^ 0x{algorithm.xor_out:0{out_digits}X}{suffix});", "}"])
    return "\n".join(lines) + "\n"


def _rust(algorithm: CrcAlgorithm, name: str) -> str:
    width = algorithm.width
    register_bits = _register_bits(algorithm)
    type_bits = _type_bits(register_bits)
    rtype = f"u{type_bits}"
    digits = max(2, (register_bits + 3) // 4)
    out_digits = max(1, (width + 3) // 4)
    shift = register_bits - width
    header = "\n".join(f"// {line}" for line in _header_lines(algorithm, name))
    table_name = f"{name.upper()}_TABLE"
    lines = [
        header,
        "",
        f"const {table_name}: [{rtype}; 256] = [",
        _format_table(_table(algorithm), digits, max(4, 64 // (digits + 4)), "", "    "),
        "];",
        "",
        f"pub fn {name}(data: &[u8]) -> {rtype} {{",
        f"    let mut crc: {rtype} = 0x{_start_register(algorithm):0{digits}X};",
        "    for &byte in data {",
    ]
    if algorithm.refin:
        step = f"{table_name}[((crc ^ byte as {rtype}) & 0xFF) as usize]"
        if register_bits > 8:
            step += " ^ (crc >> 8)"
    else:
        step = f"{table_name}[(((crc >> {register_bits - 8}) ^ byte as {rtype}) & 0xFF) as usize]"
        if register_bits > 8:
            step += " ^ (crc << 8)"
        if register_bits < type_bits:
            step = f"({step}) & 0x{(1 << register_bits) - 1:0{digits}X}"
    lines.append(f"        crc = {step};")
    lines.append("    }")
    if shift:
        lines.append(f"    crc >>= {shift};")
    if algorithm.refout != algorithm.refin:
        lines.append(f"    crc = crc.reverse_bits() >> ({type_bits} - {width});")
    lines.extend([f"    crc ^ 0x{algorithm.xor_out:0{out_digits}X}", "}"])
    return "\n".join(lines) + "\n"
