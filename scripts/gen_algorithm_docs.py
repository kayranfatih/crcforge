"""Generate docs/algorithms.md from the built-in catalog.

Usage:
    python scripts/gen_algorithm_docs.py          # write the file
    python scripts/gen_algorithm_docs.py --check  # fail if it is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from crcforge.catalog import get_algorithms  # noqa: E402
from crcforge.crc import CrcAlgorithm, format_value  # noqa: E402

OUTPUT = ROOT / "docs" / "algorithms.md"


def render() -> str:
    crcs = [a for a in get_algorithms(family="crc") if isinstance(a, CrcAlgorithm)]
    checksums = get_algorithms(family="checksum")
    lines = [
        "# Algorithms",
        "",
        "<!-- Generated by scripts/gen_algorithm_docs.py. Do not edit by hand. -->",
        "",
        f"CRCForge has {len(crcs) + len(checksums)} algorithms: all {len(crcs)} CRCs from the "
        "[RevEng CRC catalogue](https://reveng.sourceforge.io/crc-catalogue/all.htm) and "
        f"{len(checksums)} checksums. Each one is tested against its published check value (the result for "
        "`123456789`). `crcforge self-test` runs that test and `crcforge info <name>` shows one entry.",
        "",
        "Names ignore case and `/`, `_` and `-` mean the same thing, so `CRC-16/MODBUS` and `crc_16_modbus` both work.",
        "",
        "## CRCs",
        "",
        "Parameters use RevEng notation. Status is RevEng's model class: *attested* means defined in a "
        "standards document and corroborated (worked example, implementation or codewords); *confirmed* means "
        "backed by a widely available implementation; *academic* means it is not confirmed that CRCs are "
        "calculated this way in the field; *third-party* means all parameters come from unofficial sources.",
        "",
        "| Name | Width | Poly | Init | RefIn | RefOut | XorOut | Check | Status | Aliases |",
        "| --- | ---: | --- | --- | :---: | :---: | --- | --- | --- | --- |",
    ]
    for algorithm in crcs:
        aliases = ", ".join(f"`{alias}`" for alias in algorithm.aliases) or ""
        lines.append(
            f"| `{algorithm.name}` | {algorithm.width} | `{format_value(algorithm.poly, algorithm.width)}` "
            f"| `{format_value(algorithm.init, algorithm.width)}` | {'yes' if algorithm.refin else 'no'} "
            f"| {'yes' if algorithm.refout else 'no'} | `{format_value(algorithm.xor_out, algorithm.width)}` "
            f"| `{format_value(algorithm.check or 0, algorithm.width)}` | {algorithm.status or ''} | {aliases} |"
        )
    lines.extend(
        [
            "",
            "## Checksums",
            "",
            "| Name | Width | Definition | Check | Aliases |",
            "| --- | ---: | --- | --- | --- |",
        ]
    )
    for checksum in checksums:
        definition = checksum.describe().split(": ", 1)[1]
        aliases = ", ".join(f"`{alias}`" for alias in checksum.aliases)
        lines.append(
            f"| `{checksum.name}` | {checksum.width} | {definition} "
            f"| `{format_value(checksum.check or 0, checksum.width)}` | {aliases} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Exit with an error if the file is out of date.")
    args = parser.parse_args()
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != content:
            print("docs/algorithms.md is out of date; run python scripts/gen_algorithm_docs.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
